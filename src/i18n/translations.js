/**
 * Translate helper function
 * @param {string} key - English term
 * @param {string} currentLang - 'English' | 'Hindi' | 'Odia' | 'Telugu'
 * @param {string} fallback - fallback string if key is not found
 */
export function translate(key, currentLang = 'English', fallback = null) {
  if (!key || typeof key !== 'string') return key || '';
  const trimmed = key.trim();
  if (!trimmed) return key;

  if (currentLang === 'English') return key;

  const langDict = translations[currentLang];
  if (langDict && langDict[trimmed]) {
    // Preserve leading and trailing whitespace
    const leading = key.match(/^\s*/)[0];
    const trailing = key.match(/\s*$/)[0];
    return leading + langDict[trimmed] + trailing;
  }

  // Case-insensitive lookup fallback
  if (langDict) {
    const lowerTrimmed = trimmed.toLowerCase();
    for (const [k, v] of Object.entries(langDict)) {
      if (k.toLowerCase() === lowerTrimmed) {
        const leading = key.match(/^\s*/)[0];
        const trailing = key.match(/\s*$/)[0];
        return leading + v + trailing;
      }
    }
  }

  return fallback !== null ? fallback : key;
}
