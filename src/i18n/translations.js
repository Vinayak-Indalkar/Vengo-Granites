/**
 * Translate helper function
 * @param {string} key - English term
 * @param {string} currentLang - 'English' | 'Hindi' | 'Odia' | 'Telugu'
 * @param {string} fallback - fallback string if key is not found
 */
export function translate(key, currentLang = 'English', fallback = null) {
  if (!key) return '';
  const langDict = translations[currentLang] || translations.English;
  if (langDict && langDict[key]) {
    return langDict[key];
  }
  // Fall back to English dictionary if not found in current language
  if (translations.English && translations.English[key]) {
    return translations.English[key];
  }
  return fallback !== null ? fallback : key;
}
